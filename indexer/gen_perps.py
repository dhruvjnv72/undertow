"""Generate src/perps.ts: price and size decimals per market, read from Exchange.getPerpetualInfo on-chain.

    python indexer/gen_perps.py        (needs: pip install eth-abi eth-utils; both come with eth-account)

Run again if Perpl lists new markets. Markets the contract does not know are skipped.
"""
import json
import sys
import urllib.request
from pathlib import Path

from eth_abi import decode
from eth_utils import keccak

ROOT = Path(__file__).resolve().parent.parent
NETWORKS = {
    143: ("https://rpc.monad.xyz", "0x34B6552d57a35a1D042CcAe1951BD1C370112a6F"),
    10143: ("https://testnet-rpc.monad.xyz", "0x1964C32f0bE608E7D29302AFF5E61268E72080cc"),
}
abi = json.loads((ROOT / "abi" / "Exchange.json").read_text())
abi = abi["abi"] if isinstance(abi, dict) else abi
fn = next(x for x in abi if x.get("type") == "function" and x["name"] == "getPerpetualInfo")


def type_of(o):
    return "(" + ",".join(type_of(c) for c in o["components"]) + ")" if o["type"] == "tuple" else o["type"]


OUT_TYPE = type_of(fn["outputs"][0])
SEL = keccak(text="getPerpetualInfo(uint256)")[:4].hex()


def rpc(url, calls):
    req = urllib.request.Request(url, json.dumps(calls).encode(), {"Content-Type": "application/json", "User-Agent": "undertow"})
    return sorted(json.loads(urllib.request.urlopen(req, timeout=60).read()), key=lambda r: r["id"])


lines = ["// Generated by indexer/gen_perps.py from Exchange.getPerpetualInfo. Keyed by chain id, then market id.",
         "export const PERPS: Record<number, Record<number, { name: string; priceDecimals: number; lotDecimals: number }>> = {"]
for chain, (url, exchange) in NETWORKS.items():
    ids = ([1, 10, 20, 31, 40, 50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150] if chain == 143
           else [16, 32, 48, 64, 256, 272, 288, 304, 320, 336, 352, 368, 384, 400, 416])
    calls = [{"jsonrpc": "2.0", "id": i, "method": "eth_call",
              "params": [{"to": exchange, "data": "0x" + SEL + f"{pid:064x}"}, "latest"]} for i, pid in enumerate(ids)]
    lines.append(f"  {chain}: {{")
    for pid, r in zip(ids, rpc(url, calls)):
        if "result" not in r:
            print(f"chain {chain} market {pid}: skipped ({r.get('error', {}).get('message')})", file=sys.stderr)
            continue
        t = decode([OUT_TYPE], bytes.fromhex(r["result"][2:]))[0]
        lines.append(f"    {pid}: {{ name: {json.dumps(t[1] or t[0])}, priceDecimals: {t[2]}, lotDecimals: {t[3]} }},")
    lines.append("  },")
lines.append("};")
out = ROOT / "indexer" / "src" / "perps.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n")
print("wrote", out)
