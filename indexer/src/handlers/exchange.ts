import { indexer } from "envio";
import { PERPS } from "../perps";

const CNS = 1e6; // collateral (AUSD) has 6 decimals

const day = (ts: number) => new Date(ts * 1000).toISOString().slice(0, 10);
const num = (v: bigint | number) => Number(v);

// Market decimals come from src/perps.ts; unknown markets are skipped so one new listing cannot break indexing.
function perp(chainId: number, perpId: bigint | number) {
  const p = PERPS[chainId]?.[Number(perpId)];
  return p ? { ...p, id: Number(perpId) } : undefined;
}
const price = (v: bigint, d: number) => num(v) / 10 ** d;
const lots = (v: bigint, d: number) => num(v) / 10 ** d;

type Ctx = any; // entity types are generated by `envio codegen` into .envio/

async function bumpDaily(context: Ctx, chainId: number, ts: number, delta: Record<string, number>) {
  const date = day(ts);
  const id = `${chainId}-${date}`;
  const cur = await context.DailyStats.getOrCreate({
    id, chainId, date, volumeUsd: 0, trades: 0, makerFeesUsd: 0, liquidations: 0, liquidatedUsd: 0,
    deleverages: 0, depositsUsd: 0, withdrawalsUsd: 0, newAccounts: 0,
  });
  const next: any = { ...cur };
  for (const [k, v] of Object.entries(delta)) next[k] = (next[k] ?? 0) + v;
  context.DailyStats.set(next);
}

async function bumpPerpDaily(context: Ctx, chainId: number, ts: number, p: { id: number; name: string },
                             delta: { volumeUsd?: number; trades?: number; liquidations?: number; liquidatedUsd?: number }) {
  const date = day(ts);
  const id = `${chainId}-${p.id}-${date}`;
  const cur = await context.PerpDailyStats.getOrCreate({
    id, chainId, perpId: p.id, perpName: p.name, date, volumeUsd: 0, trades: 0, liquidations: 0, liquidatedUsd: 0,
  });
  context.PerpDailyStats.set({
    ...cur,
    volumeUsd: cur.volumeUsd + (delta.volumeUsd ?? 0),
    trades: cur.trades + (delta.trades ?? 0),
    liquidations: cur.liquidations + (delta.liquidations ?? 0),
    liquidatedUsd: cur.liquidatedUsd + (delta.liquidatedUsd ?? 0),
  });
}

const eid = (e: any) => `${e.chainId}-${e.block.number}-${e.logIndex}`;

const sideOf = (t: bigint | number) => (Number(t) === 0 ? "Long" : "Short");

function posEvent(context: Ctx, e: any, p: { id: number; name: string }, f: {
  kind: string; accountId: bigint | number; positionType: bigint | number; price?: number; sizeBefore?: number; sizeAfter?: number;
  leverage?: number; realizedPnlUsd?: number; fundingPaidUsd?: number;
}) {
  context.PositionEvent.set({
    id: eid(e), chainId: e.chainId, perpId: p.id, perpName: p.name, accountId: num(f.accountId), kind: f.kind, side: sideOf(f.positionType),
    price: f.price ?? undefined, sizeBefore: f.sizeBefore ?? undefined, sizeAfter: f.sizeAfter ?? undefined, leverage: f.leverage ?? undefined,
    realizedPnlUsd: f.realizedPnlUsd ?? undefined, fundingPaidUsd: f.fundingPaidUsd ?? undefined, block: e.block.number, timestamp: e.block.timestamp,
  });
}

indexer.onEvent({ contract: "Exchange", event: "PositionOpenedV2" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  posEvent(context, event, p, { kind: "opened", accountId: event.params.accountId, positionType: event.params.positionType,
    price: price(event.params.pricePNS, p.priceDecimals), sizeBefore: 0, sizeAfter: lots(event.params.lotLNS, p.lotDecimals),
    leverage: num(event.params.leverageHdths) / 100 });
});

indexer.onEvent({ contract: "Exchange", event: "PositionIncreasedV2" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  posEvent(context, event, p, { kind: "increased", accountId: event.params.accountId, positionType: event.params.positionType,
    price: price(event.params.pricePNS, p.priceDecimals), sizeBefore: lots(event.params.startLotLNS, p.lotDecimals),
    sizeAfter: lots(event.params.endLotLNS, p.lotDecimals), leverage: num(event.params.leverageHdths) / 100 });
});

indexer.onEvent({ contract: "Exchange", event: "PositionDecreased" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  posEvent(context, event, p, { kind: "decreased", accountId: event.params.accountId, positionType: event.params.positionType,
    sizeBefore: lots(event.params.startLotLNS, p.lotDecimals), sizeAfter: lots(event.params.endLotLNS, p.lotDecimals),
    realizedPnlUsd: num(event.params.deltaPnlCNS) / CNS, fundingPaidUsd: num(event.params.fundingCNS) / CNS });
});

indexer.onEvent({ contract: "Exchange", event: "PositionClosed" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  posEvent(context, event, p, { kind: "closed", accountId: event.params.accountId, positionType: event.params.positionType,
    price: price(event.params.pricePNS, p.priceDecimals), sizeAfter: 0,
    realizedPnlUsd: num(event.params.deltaPnlCNS) / CNS, fundingPaidUsd: num(event.params.fundingCNS) / CNS });
});

indexer.onEvent({ contract: "Exchange", event: "PositionInverted" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  // The position flips side: realized profit belongs to the side being closed; the new position is positionType.
  posEvent(context, event, p, { kind: "flipped", accountId: event.params.accountId, positionType: event.params.positionType,
    price: price(event.params.pricePNS, p.priceDecimals), sizeBefore: lots(event.params.startLotLNS, p.lotDecimals),
    sizeAfter: lots(event.params.endLotLNS, p.lotDecimals), leverage: num(event.params.leverageHdths) / 100,
    realizedPnlUsd: num(event.params.deltaPnlCNS) / CNS, fundingPaidUsd: num(event.params.fundingCNS) / CNS });
});

indexer.onEvent({ contract: "Exchange", event: "MakerOrderFilledV2" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  const px = price(event.params.pricePNS, p.priceDecimals);
  const size = lots(event.params.lotLNS, p.lotDecimals);
  const notional = px * size;
  const fee = num(event.params.feeCNS) / CNS;
  const ts = event.block.timestamp;
  context.Trade.set({
    id: eid(event), chainId: event.chainId, perpId: p.id, perpName: p.name, makerAccountId: num(event.params.accountId),
    price: px, size, notionalUsd: notional, makerFeeUsd: fee, block: event.block.number, timestamp: ts,
  });
  await bumpDaily(context, event.chainId, ts, { volumeUsd: notional, trades: 1, makerFeesUsd: fee });
  await bumpPerpDaily(context, event.chainId, ts, p, { volumeUsd: notional, trades: 1 });
});

indexer.onEvent({ contract: "Exchange", event: "PositionLiquidated" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  const liqPrice = price(event.params.liqPricePNS, p.priceDecimals);
  const size = lots(event.params.liqLotLNS, p.lotDecimals);
  const ts = event.block.timestamp;
  context.Liquidation.set({
    id: eid(event), chainId: event.chainId, perpId: p.id, perpName: p.name, accountId: num(event.params.posAccountId),
    side: Number(event.params.positionType) === 0 ? "Long" : "Short",
    markPrice: price(event.params.markPricePNS, p.priceDecimals), liqPrice, liquidatedSize: size,
    remainingSize: lots(event.params.posLotLNS, p.lotDecimals), notionalUsd: liqPrice * size,
    onOrderBook: event.params.onOrderBook, block: event.block.number, timestamp: ts,
  });
  posEvent(context, event, p, { kind: "liquidated", accountId: event.params.posAccountId, positionType: event.params.positionType,
    price: liqPrice, sizeBefore: lots(event.params.posLotLNS + event.params.liqLotLNS, p.lotDecimals),
    sizeAfter: lots(event.params.posLotLNS, p.lotDecimals), realizedPnlUsd: num(event.params.deltaPnlCNS) / CNS,
    fundingPaidUsd: num(event.params.fundingCNS) / CNS });
  await bumpDaily(context, event.chainId, ts, { liquidations: 1, liquidatedUsd: liqPrice * size });
  await bumpPerpDaily(context, event.chainId, ts, p, { liquidations: 1, liquidatedUsd: liqPrice * size });
});

indexer.onEvent({ contract: "Exchange", event: "PositionDeleveragedV2" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  const ts = event.block.timestamp;
  context.Deleverage.set({
    id: eid(event), chainId: event.chainId, perpId: p.id, perpName: p.name, accountId: num(event.params.accountId),
    side: Number(event.params.positionType) === 0 ? "Long" : "Short", forceClose: event.params.forceClose,
    markPrice: price(event.params.markPricePNS, p.priceDecimals),
    deleveragePrice: price(event.params.deleveragePricePNS, p.priceDecimals),
    closedSize: lots(event.params.startLotLNS - event.params.endLotLNS, p.lotDecimals),
    block: event.block.number, timestamp: ts,
  });
  posEvent(context, event, p, { kind: "deleveraged", accountId: event.params.accountId, positionType: event.params.positionType,
    price: price(event.params.deleveragePricePNS, p.priceDecimals), sizeBefore: lots(event.params.startLotLNS, p.lotDecimals),
    sizeAfter: lots(event.params.endLotLNS, p.lotDecimals), realizedPnlUsd: num(event.params.deltaPnlCNS) / CNS,
    fundingPaidUsd: num(event.params.fundingCNS) / CNS });
  await bumpDaily(context, event.chainId, ts, { deleverages: 1 });
});

indexer.onEvent({ contract: "Exchange", event: "CollateralDeposit" }, async ({ event, context }) => {
  const amount = num(event.params.amountCNS) / CNS;
  const ts = event.block.timestamp;
  context.CashFlow.set({ id: eid(event), chainId: event.chainId, accountId: num(event.params.accountId), kind: "deposit",
    amountUsd: amount, block: event.block.number, timestamp: ts });
  await bumpDaily(context, event.chainId, ts, { depositsUsd: amount });
});

indexer.onEvent({ contract: "Exchange", event: "CollateralWithdrawal" }, async ({ event, context }) => {
  const amount = num(event.params.amountCNS) / CNS;
  const ts = event.block.timestamp;
  context.CashFlow.set({ id: eid(event), chainId: event.chainId, accountId: num(event.params.accountId), kind: "withdrawal",
    amountUsd: amount, block: event.block.number, timestamp: ts });
  await bumpDaily(context, event.chainId, ts, { withdrawalsUsd: amount });
});

indexer.onEvent({ contract: "Exchange", event: "AccountCreated" }, async ({ event, context }) => {
  const ts = event.block.timestamp;
  context.Account.set({ id: `${event.chainId}-${event.params.id}`, chainId: event.chainId, accountId: num(event.params.id),
    address: event.params.account, createdBlock: event.block.number, createdAt: ts });
  await bumpDaily(context, event.chainId, ts, { newAccounts: 1 });
});

indexer.onEvent({ contract: "Exchange", event: "FundingEventCompleted" }, async ({ event, context }) => {
  const p = perp(event.chainId, event.params.perpId);
  if (!p) return;
  context.FundingEvent.set({ id: eid(event), chainId: event.chainId, perpId: p.id, perpName: p.name,
    fundingBlock: num(event.params.fundingEventBlock), actualRatePct100k: num(event.params.actualRatePct100k),
    timestamp: event.block.timestamp });
});
